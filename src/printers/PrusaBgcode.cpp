#include "printers/PrusaBgcode.h"

#include <binarize/binarize.hpp>

#include <QByteArrayView>
#include <QFile>
#include <QMap>
#include <QRegularExpression>
#include <QTemporaryFile>

#include <cerrno>
#include <cstdio>
#include <cstring>
#include <memory>
#include <stdexcept>

namespace {
void requireSuccess(bgcode::core::EResult result)
{
    if (result != bgcode::core::EResult::Success)
        throw std::runtime_error(std::string(bgcode::core::translate_result(result)));
}
}

QByteArray prusaBgcode(const QByteArray &gcode)
{
    using namespace bgcode;
    binarize::Binarizer writer;
    writer.set_enabled(true);
    auto &binary = writer.get_binary_data();
    binary.file_metadata.raw_data.emplace_back("Prepared by", "Mirdain Forward");

    QMap<QByteArray, QByteArray> metadata;
    const QRegularExpression thumbnailBegin("^(thumbnail(?:_JPG|_QOI)?) begin ([0-9]+)x([0-9]+) [0-9]+$");
    QByteArray thumbnailEnd;
    QByteArray thumbnailData;
    for (qsizetype start = 0; start < gcode.size();) {
        auto end = gcode.indexOf('\n', start);
        if (end < 0) end = gcode.size();
        auto line = QByteArrayView(gcode).sliced(start, end - start).trimmed();
        start = end + 1;
        if (!line.startsWith(';')) continue;
        const auto comment = line.sliced(1).trimmed();
        if (comment.startsWith("generated by "))
            binary.file_metadata.raw_data.emplace_back("Producer", comment.sliced(13).toByteArray().toStdString());
        if (!thumbnailEnd.isEmpty()) {
            if (comment == thumbnailEnd) {
                const auto decoded = QByteArray::fromBase64(thumbnailData);
                auto &data = binary.thumbnails.back().data;
                const auto *bytes = reinterpret_cast<const std::byte *>(decoded.constData());
                data.assign(bytes, bytes + decoded.size());
                thumbnailEnd.clear();
                thumbnailData.clear();
            } else {
                thumbnailData.append(comment);
            }
            continue;
        }
        if (comment.startsWith("thumbnail")) {
            const auto match = thumbnailBegin.match(QString::fromUtf8(comment));
            if (match.hasMatch()) {
                auto &thumbnail = binary.thumbnails.emplace_back();
                const auto name = match.captured(1);
                thumbnail.params.format = uint16_t(name.endsWith("_JPG") ? core::EThumbnailFormat::JPG
                    : name.endsWith("_QOI") ? core::EThumbnailFormat::QOI : core::EThumbnailFormat::PNG);
                thumbnail.params.width = match.captured(2).toUShort();
                thumbnail.params.height = match.captured(3).toUShort();
                thumbnailEnd = name.toUtf8() + " end";
                continue;
            }
        }
        const auto equals = comment.indexOf('=');
        if (equals > 0)
            metadata.insert(comment.first(equals).trimmed().toByteArray(), comment.sliced(equals + 1).trimmed().toByteArray());
    }

    // The required metadata blocks also give the printer its preview details.
    binary.printer_metadata.raw_data.emplace_back("Prepared by", "Mirdain Forward");
    binary.print_metadata.raw_data.emplace_back("Prepared by", "Mirdain Forward");
    binary.slicer_metadata.raw_data.emplace_back("Prepared by", "Mirdain Forward");
    for (auto it = metadata.cbegin(); it != metadata.cend(); ++it)
        binary.slicer_metadata.raw_data.emplace_back(it.key().toStdString(), it.value().toStdString());
    for (const auto *key : {"printer_model", "filament_type", "filament_abrasive", "nozzle_diameter", "nozzle_high_flow",
             "bed_temperature", "layer_height", "temperature", "max_layer_z", "extruder_colour", "objects_info"}) {
        if (metadata.contains(key))
            binary.printer_metadata.raw_data.emplace_back(key, metadata.value(key).toStdString());
    }
    for (const auto *key : {"filament used [mm]", "filament used [cm3]", "filament used [g]", "filament cost",
             "total filament used [g]", "total filament cost", "total toolchanges",
             "estimated printing time (normal mode)", "estimated printing time (silent mode)"}) {
        if (metadata.contains(key)) {
            const auto value = metadata.value(key).toStdString();
            binary.printer_metadata.raw_data.emplace_back(key, value);
            binary.print_metadata.raw_data.emplace_back(key, value);
        }
    }

    QTemporaryFile temporary;
    if (!temporary.open()) throw std::runtime_error(temporary.errorString().toStdString());
    temporary.close();
#ifdef Q_OS_WIN
    auto *stream = _wfopen(reinterpret_cast<const wchar_t *>(temporary.fileName().utf16()), L"w+b");
#else
    auto *stream = std::fopen(QFile::encodeName(temporary.fileName()).constData(), "w+b");
#endif
    std::unique_ptr<FILE, decltype(&std::fclose)> output(stream, &std::fclose);
    if (!output) throw std::runtime_error(std::strerror(errno));
    binarize::BinarizerConfig config;
    config.gcode_encoding = core::EGCodeEncodingType::MeatPackComments;
    config.compression.gcode = core::ECompressionType::Heatshrink_12_4;
    config.compression.slicer_metadata = core::ECompressionType::Deflate;
    requireSuccess(writer.initialize(*output, config));
    auto commands = gcode.toStdString();
    if (commands.back() != '\n') commands += '\n';
    requireSuccess(writer.append_gcode(commands));
    requireSuccess(writer.finalize());
    std::rewind(output.get());
    QFile encoded;
    if (!encoded.open(output.get(), QIODevice::ReadOnly))
        throw std::runtime_error(encoded.errorString().toStdString());
    auto result = encoded.readAll();
    if (encoded.error() != QFileDevice::NoError)
        throw std::runtime_error(encoded.errorString().toStdString());
    return result;
}
